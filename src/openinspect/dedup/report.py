def similarity_summary(audit: Audit) -> str:
    run, t = audit.run, audit.thresholds
    lines = _header("M3 similarity summary", audit)
    lines += ["## Run", ""]
    lines += _table(
        ["item", "value"],
        [
            [
                "model",
                f"`{run.model_id}` at revision `{run.revision[:12]}` (weights SHA-256 "
                f"`{run.weights_sha256[:12]}…`), {run.dim} dimensions",
            ],
            ["preprocessing, backend", f"`{run.preprocessing_version}`, `{run.backend}`"],
            ["perceptual hash", f"`{run.phash_version}` (64-bit DCT hash); dHash from ingest"],
            [
                "images",
                f"{run.images:,}; failed to read or decode: {len(run.failures)} "
                f"(undecodable at ingest: {run.skipped_at_ingest})",
            ],
        ],
    )
    lines += ["", "## Inputs", ""]
    lines += _table(
        [
            "source",
            "images",
            "annotations",
            "with features",
            "failed",
            "original splits",
            "group key",
        ],
        [
            [
                f"`{s.source}`",
                _int(s.images),
                _int(s.annotations),
                _int(s.embedded),
                _int(s.failed),
                " / ".join(f"{k} {v:,}" for k, v in s.splits.items()),
                s.group_key or "none",
            ]
            for s in run.sources
        ],
    )
    lines += ["", "## Thresholds (protocol section 6, applied mechanically)", ""]
    lines += _table(
        ["level", "value", "category it opens"],
        [
            ["near", _f(t.near, 4), "`NEAR_DUPLICATE` at or above"],
            ["family", _f(t.family, 4), "`SAME_FAMILY_OR_SCENE` from here up to near"],
            ["review", _f(t.review, 4), "`REVIEW_REQUIRED` from here up to family"],
            [
                "pHash candidate",
                f"<= {t.phash_candidate} bits",
                "`REVIEW_REQUIRED` when the hash is this close but the cosine is under review",
            ],
        ],
    )
    fallbacks = [f"`{p.source}` {p.pool}: {p.fallback}" for p in t.from_pools if p.fallback]
    lines += [""]
    if fallbacks:
        lines += ["Fallbacks the rule applied (rule 5):", ""]
        lines += [f"- {f}" for f in fallbacks]
        lines += [""]
    if t.review == t.family:
        lines += [
            "The review and family thresholds coincide, so no pair is `REVIEW_REQUIRED` by cosine "
            "alone; that category holds only pairs whose pHash is close while the cosine is not.",
            "",
        ]
    lines += [
        "How each value was obtained: [threshold-calibration.md](threshold-calibration.md).",
        "",
        "## Exact duplicates",
        "",
        f"Identical SHA-256: {audit.hash_audit.sha256_equal_pairs:,} pairs in "
        f"{audit.hash_audit.sha256_equal_groups:,} groups over all {run.images:,} images, "
        f"{audit.cross_source.sha256_equal_pairs:,} of them across sources.",
        "",
        "## Candidate pairs by suggested category",
        "",
        "Counts of image pairs; in brackets the pairs whose two images sit in different official "
        "splits of the same source.",
        "",
    ]
    scopes = sorted({c.scope for c in audit.categories}, key=lambda s: (s == "across", s))
    rows = []
    for scope in scopes:
        cells = [f"`{scope}`"]
        for category in CATEGORIES:
            count = next(
                (c for c in audit.categories if c.scope == scope and c.category == category), None
            )
            cells.append(DASH if count is None else f"{count.pairs:,} ({count.cross_split:,})")
        rows.append(cells)
    lines += _table(["scope", *(f"`{c}`" for c in CATEGORIES)], rows)
    lines += ["", "## Most similar other image of the same source (no threshold)", ""]
    lines += _table(
        [
            "source",
            "images",
            "top-1 cosine: median (p05 to p95)",
            "max",
            ">= review",
            ">= family",
            ">= near",
            "nearest image of all is in another source (>= family)",
        ],
        [
            [
                f"`{s.source}`",
                _int(s.images),
                _q(s.within_source),
                _f(s.within_source.maximum if s.within_source else None),
                _share(s.share_review),
                _share(s.share_family),
                _share(s.share_near),
                f"{s.nearest_is_other_source:,} ({s.other_source_family:,})",
            ]
            for s in audit.top1
        ],
    )
    keyed = [s for s in audit.top1 if s.top1_same_group is not None]
    if keyed:
        lines += ["", "Does the most similar image share the source's own key?", ""]
        lines += _table(
            ["source", "shares the group key", "chance", "shares the subgroup key", "chance"],
            [_key_row(s) for s in keyed],
        )
    lines += ["", _figure("top1-cdf.svg", "Top-1 cosine per source"), ""]
    lines += _hash_section(audit)
    lines += _cross_source_section(audit)
    return "\n".join(lines) + "\n"


def _key_row(s: Top1Stats) -> list[str]:
    return [
        f"`{s.source}`",
        _share(s.top1_same_group),
        _share(s.chance_same_group),
        _share(s.top1_same_subgroup),
        _share(s.chance_same_subgroup),
    ]


def _hash_section(audit: Audit) -> list[str]:
    h = audit.hash_audit
    lines = [
        "## Hash audit",
        "",
        f"Pairs within a Hamming distance, at the PCB-IND authors' distance ({h.authors_distance} "
        f"bits) and at the calibrated candidate distance ({h.candidate_distance} bits).",
        "",
    ]
    lines += _table(
        [
            "hash",
            "bits",
            "scope",
            "pairs",
            "same subgroup",
            "same group, other subgroup",
            "other group",
            "cross-split",
        ],
        [
            [
                s.algorithm,
                str(s.distance),
                f"`{s.scope}`",
                _int(s.pairs),
                _int(s.same_subgroup),
                _int(s.same_group_other_subgroup),
                _int(s.other_group),
                _int(s.cross_split),
            ]
            for s in h.scopes
        ],
    )
    lines += [
        "",
        "Share of pHash-candidate pairs whose two images also share a family-level similarity "
        "group: "
        + "; ".join(f"`{k}` {_share(v)}" for k, v in sorted(h.phash_in_family_group.items()))
        + ".",
        "",
    ]
    return lines


def _cross_source_section(audit: Audit) -> list[str]:
    c = audit.cross_source
    lines = ["## Across sources", ""]
    lines += _table(
        ["level", "sources", "pairs", "images of the first", "images of the second"],
        [
            [
                e.level,
                f"`{e.source_a}` / `{e.source_b}`",
                _int(e.pairs),
                _int(e.images_a),
                _int(e.images_b),
            ]
            for e in c.edges
        ],
    )
    if c.top_pairs:
        lines += ["", "Most similar pairs across sources:", ""]
        lines += _table(
            ["cosine", "image", "image"],
            [[_f(s, 4), f"`{a}`", f"`{b}`"] for a, b, s in c.top_pairs],
        )
    lines += [""]
    return lines


