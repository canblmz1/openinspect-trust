def _agreement_row(level: str, key: str, a: PartitionAgreement) -> list[str]:
    return [
        level,
        key,
        _int(a.n_images),
        _f(a.pair_precision),
        _f(a.pair_recall),
        _f(a.adjusted_rand),
        _f(a.homogeneity),
        _f(a.completeness),
        _f(a.multi_member_purity),
    ]


def _overlap_section(audit: Audit, source: str, title: str) -> list[str]:
    overlaps: list[KeyOverlap] = [
        o for level in audit.levels for o in level.key_overlap if o.source == source
    ]
    if not overlaps:
        return []
    lines = [f"## {title}", ""]
    rows = []
    for o in overlaps:
        rows.append(_agreement_row(o.level, o.key_group_name, o.vs_group))
        rows.append(_agreement_row(o.level, o.key_subgroup_name, o.vs_subgroup))
    lines += [
        "Pair precision: of the image pairs that share a similarity group, the share that also share "
        "the key. Pair recall: of the pairs that share the key, the share that also share a "
        "similarity group.",
        "",
    ]
    lines += _table(
        [
            "level",
            "key",
            "images",
            "pair precision",
            "pair recall",
            "adjusted Rand",
            "homogeneity",
            "completeness",
            "majority-key purity",
        ],
        rows,
    )
    lines += ["", "What the similar pairs (edges) are, in terms of the key:", ""]
    lines += _table(
        [
            "level",
            "edges",
            "same subgroup",
            "same group, other subgroup",
            "other group",
            "cross-split edges: same subgroup / same group / other group",
        ],
        [
            [
                o.level,
                _int(o.edge_mix.edges),
                _int(o.edge_mix.same_subgroup),
                _int(o.edge_mix.same_group_other_subgroup),
                _int(o.edge_mix.other_group),
                f"{o.edge_mix.cross_split_same_subgroup:,} / {o.edge_mix.cross_split_same_group_other_subgroup:,} / {o.edge_mix.cross_split_other_group:,}",
            ]
            for o in overlaps
        ],
    )
    with_splits = [o for o in overlaps if o.key_cross_split_images is not None]
    if with_splits:
        lines += [
            "",
            f"Images in a {with_splits[0].key_group_name} that spans splits (key) and images in a "
            "similarity group that spans splits (similarity):",
            "",
        ]
        lines += _table(
            [
                "level",
                "key spans splits",
                "similarity spans splits",
                "both",
                "key only",
                "similarity only",
                "neither",
                "crossing groups holding several keys",
            ],
            [
                [
                    o.level,
                    _int(o.key_cross_split_images),
                    _int(o.similarity_cross_split_images),
                    _int(o.both),
                    _int(o.only_key),
                    _int(o.only_similarity),
                    _int(o.neither),
                    _int(o.cross_split_groups_with_several_keys),
                ]
                for o in with_splits
            ],
        )
    lines += [""]
    return lines


