# --------------------------------------------------------------------------- performance


def _gb(value: int | None) -> str:
    return DASH if value is None else f"{value / 1e9:.2f} GB"


def performance(audit: Audit) -> str:
    lines = _header("M3 performance", audit)
    p = audit.performance
    if p is None:
        lines += ["No performance record."]
        return "\n".join(lines) + "\n"
    rows = []
    for stage in p.stages:
        rate = f"{stage.images / stage.seconds:.1f}" if stage.images and stage.seconds else DASH
        rows.append(
            [
                stage.stage,
                f"{stage.seconds:,.1f}",
                _int(stage.images),
                rate,
                _gb(stage.peak_ram_bytes),
                stage.note or "",
            ]
        )
    lines += ["## Stages", ""]
    lines += _table(["stage", "seconds", "images", "images per second", "peak RAM", "note"], rows)
    lines += [
        "",
        "## Totals",
        "",
    ]
    lines += _table(
        ["item", "value"],
        [
            [
                "wall time of the stages above",
                f"{p.total_seconds:,.0f} s ({p.total_seconds / 60:.1f} min)",
            ],
            [
                "embedding throughput (cache build)",
                f"{_f(p.embed_images_per_second, 1)} images/s overall, {_f(p.embed_model_images_per_second, 1)} images/s in the model",
            ],
            [
                "embedding cache",
                f"{p.cache_files:,} files, {p.cache_bytes / 1e6:.1f} MB on disk ({p.cache_logical_bytes / 1e6:.1f} MB of vectors)",
            ],
            ["peak RAM", _gb(p.peak_ram_bytes)],
            ["processor", p.cpu or DASH],
            ["note", p.note or DASH],
        ],
    )
    lines += [
        "",
        "Artifacts (SHA-256):",
        "",
    ]
    lines += _table(
        ["file", "SHA-256"],
        [[f"`{name}`", f"`{digest}`"] for name, digest in sorted(audit.artifacts.items())],
    )
    lines += [""]
    return "\n".join(lines) + "\n"


