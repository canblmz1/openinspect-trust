# ------------------------------------------------------------------------------ format


def _int(value: int | None) -> str:
    return DASH if value is None else f"{value:,}"


def _f(value: float | None, digits: int = 3) -> str:
    return DASH if value is None else f"{value:.{digits}f}"


def _pct(part: int | float | None, whole: int | float | None) -> str:
    if part is None or not whole:
        return DASH
    return f"{100 * part / whole:.1f}%"


def _share(value: float | None) -> str:
    return DASH if value is None else f"{100 * value:.1f}%"


def _ci(interval: Interval | None) -> str:
    return DASH if interval is None else f"[{interval.low:.3f}, {interval.high:.3f}]"


def _q(q: Quantiles | None, digits: int = 3) -> str:
    if q is None:
        return DASH
    return f"{q.median:.{digits}f} ({q.p05:.{digits}f} to {q.p95:.{digits}f})"


def _p(value: float, n: int) -> str:
    return f"< {1 / n:.3f}" if value == 0 else f"{value:.3f}"


def _p_text(value: float, n: int) -> str:
    return f"< {1 / n:.3f}" if value == 0 else f"= {value:.3f}"


def _table(headers: Sequence[str], rows: Sequence[Sequence[str]]) -> list[str]:
    lines = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    lines.extend("| " + " | ".join(row) + " |" for row in rows)
    return lines


def slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-") or "x"


def _header(title: str, audit: Audit) -> list[str]:
    commit = audit.run.code_commit
    code = (
        DASH
        if commit is None
        else f"`{commit[:12]}`" + (" with uncommitted changes" if audit.run.code_dirty else "")
    )
    return [
        f"# {title}",
        "",
        f"{SOURCE_LINE} Rules: {PROTOCOL} (frozen before any leakage number was computed) and "
        f"{AMENDMENT}. Code: {code}; seed {audit.run.seed}.",
        "",
        VOCABULARY,
        "",
    ]


def _sources(audit: Audit) -> list[str]:
    return [s.source for s in audit.run.sources]


def _level(audit: Audit, name: str) -> LevelResult | None:
    return next((level for level in audit.levels if level.level == name), None)


def primary_level(audit: Audit, source: str) -> str:
    """The chaining rule (protocol section 8): ``near`` if the source chains at ``family``."""
    family = _level(audit, "family")
    return "near" if family is not None and source in family.chained_sources else "family"


# ------------------------------------------------------------------------------ figures


def _figure(name: str, alt: str) -> str:
    return f"![{alt}](figures/{name})"


def figures(audit: Audit) -> dict[str, str]:
    t = audit.thresholds
    marks = [Marker(t.review, "review"), Marker(t.family, "family"), Marker(t.near, "near")]
    if t.review == t.family:
        marks = [Marker(t.family, "review = family"), Marker(t.near, "near")]
    out: dict[str, str] = {}
    cdfs = [Series(s.source, s.cdf) for s in audit.top1 if s.cdf]
    if cdfs:
        low = min((s.within_source.p05 for s in audit.top1 if s.within_source), default=0.0)
        x0 = max(0.0, int(low * 10) / 10)
        out["top1-cdf.svg"] = line_chart(
            "Most similar other image of the same source",
            "cosine similarity",
            "share of images at or below",
            [Series(s.name, [p for p in s.points if p[0] >= x0]) for s in cdfs],
            x_range=(x0, 1.0),
            y_range=(0.0, 1.0),
            markers=marks,
        )
    pools = [p for p in audit.pools if p.roc]
    if pools:
        out["roc.svg"] = line_chart(
            "ROC against group labels",
            "false positive rate",
            "true positive rate (recall)",
            [Series(f"{p.source} {p.pool}", p.roc) for p in pools]
            + [Series("chance", [(0.0, 0.0), (1.0, 1.0)], color="#bbbbbb", dashed=True)],
            x_range=(0.0, 1.0),
            y_range=(0.0, 1.0),
        )
        out["pr.svg"] = line_chart(
            "Precision and recall against group labels",
            "recall",
            "precision",
            [Series(f"{p.source} {p.pool}", p.pr) for p in pools],
            x_range=(0.0, 1.0),
            y_range=(0.0, 1.0),
        )
    for pool in audit.pools:
        if not pool.histogram:
            continue
        x0 = max(-1.0, int(min(c for c, _, _ in pool.histogram) * 10) / 10 - 0.1)
        top = max(max(pos, neg) for _, pos, neg in pool.histogram)
        out[f"histogram-{slug(pool.source)}-{slug(pool.pool)}.svg"] = line_chart(
            f"{pool.source}: cosine of positive and negative pairs ({pool.pool})",
            "cosine similarity (0.01 bins)",
            "share of the class's pairs",
            [
                Series("positive (same group)", [(c, pos) for c, pos, _ in pool.histogram]),
                Series("negative (other group)", [(c, neg) for c, _, neg in pool.histogram]),
            ],
            x_range=(x0, 1.0),
            y_range=(0.0, max(top * 1.1, 0.01)),
            markers=marks,
        )
    if audit.synthetic is not None and audit.synthetic.by_transform:
        rows = audit.synthetic.by_transform
        out["synthetic.svg"] = bar_chart(
            "Synthetic copies at or above the near threshold",
            "transform",
            "share of copies",
            [r.transform.replace("_", " ") for r in rows],
            [Bars("share >= near", [r.share_near for r in rows])],
            y_max=1.0,
            width=760,
        )
    crossing = _crossing_bars(audit)
    if crossing is not None:
        out["cross-split.svg"] = crossing
    percolation = _percolation_chart(audit, marks)
    if percolation is not None:
        out["percolation.svg"] = percolation
    return out


def _crossing_bars(audit: Audit) -> str | None:
    categories: list[str] = []
    observed: list[float] = []
    expected: list[float] = []
    for level in audit.levels:
        for leak in level.leakage:
            baseline = level.permutation.get(leak.source)
            if leak.has_splits and baseline is not None:
                categories.append(f"{leak.source} {level.level}")
                observed.append(float(leak.groups_crossing_any))
                expected.append(round(baseline.null_mean, 1))
    if not categories:
        return None
    return bar_chart(
        "Similarity groups that cross a split boundary",
        "source and level",
        "groups",
        categories,
        [Bars("official split", observed), Bars("random splits (mean)", expected)],
        width=760,
    )


def _percolation_chart(audit: Audit, marks: list[Marker]) -> str | None:
    series: list[Series] = []
    sizes = {s.source: s.images for s in audit.run.sources}
    lows: list[float] = []
    for source in _sources(audit):
        rows = sorted(
            (r for r in audit.percolation if r.source == source), key=lambda r: r.threshold
        )
        if rows and sizes.get(source):
            series.append(Series(source, [(r.threshold, r.largest / sizes[source]) for r in rows]))
            lows.append(rows[0].threshold)
    if not series:
        return None
    return line_chart(
        "Largest similarity group as the threshold drops",
        "cosine threshold",
        "largest group / images of the source",
        series,
        x_range=(int(min(lows) * 100) / 100, 1.0),
        y_range=(0.0, 1.0),
        markers=marks,
    )


