def render_all(readiness: Readiness) -> dict[str, str]:
    return {f"{FOLDER}/{name}": render(readiness) for name, render in RENDERERS.items()}


def write_reports(root: Path, readiness: Readiness) -> list[Path]:
    written: list[Path] = []
    for path, text in render_all(readiness).items():
        replace_bytes(root / path, text.encode("utf-8"))
        written.append(root / path)
    return written
