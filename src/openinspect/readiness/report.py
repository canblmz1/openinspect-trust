from openinspect.readiness.models import Readiness

FOLDER = "reports/m5_5"
SPLITS = ("train", "val", "test", "excluded")


def _n(value: int) -> str:
    return f"{value:,}"


def _p(value: float | None) -> str:
    return "—" if value is None else f"{100 * value:.1f}%"


def _f(value: float | None, digits: int = 3) -> str:
    return "—" if value is None else f"{value:.{digits}f}"


def _header(r: Readiness, title: str) -> list[str]:
    v = r.human_validation
    commit = (r.provenance.code_commit or "unknown")[:12]
    statement = (
        f"**Human validation: {v['status']}.** Reviewed pairs: {v['reviewed']} / {v['queued']} "
        f"(`{v['queue']}`)."
    )
    if v.get("limitation"):
        statement += f" {v['limitation']}"
    return [
        f"# {title}",
        "",
        f"Generated by `{r.provenance.command}` from `artifacts/m5_5/readiness.json` (re-render with "
        f"`openinspect readiness report`). Release {r.provenance.release}; code `{commit}`"
        f"{' (uncommitted changes)' if r.provenance.code_dirty else ''}; design seeds "
        f"{', '.join(str(s) for s in r.provenance.design_seeds)}; split seed {r.provenance.split_seed}.",
        "",
        statement,
        "",
        "Vocabulary: a *visual similarity component* is a machine-detected potential leakage group "
        "(an embedding-defined component), not proof that two images show one physical board.",
        "",
    ]


def _table(header: Sequence[str], rows: Sequence[Sequence[object]]) -> list[str]:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return lines


def _split_rows(
    items: Mapping[str, Mapping[str, int]], sources: Sequence[str]
) -> list[list[object]]:
    rows: list[list[object]] = []
    for split in SPLITS:
        if split in items:
            counts = items[split]
            rows.append(
                [f"`{split}`", _n(sum(counts.values())), *(_n(counts.get(s, 0)) for s in sources)]
            )
    return rows


def _sources(r: Readiness) -> list[str]:
    return sorted(r.negatives.available)


