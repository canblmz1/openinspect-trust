def controlled_design(r: Readiness) -> str:
    sources = _sources(r)
    e = r.estimand
    lines = _header(r, "M5.5: the A0/A1 estimand and the controlled designs")
    lines += [
        "## Why A0 - A1 is not a pure leakage effect",
        "",
        *_table(
            ["", "test items", *(f"`{s}`" for s in sources)],
            [
                ["A0 test", _n(sum(e.a0_test.values())), *(_n(e.a0_test[s]) for s in sources)],
                ["A1 test", _n(sum(e.a1_test.values())), *(_n(e.a1_test[s]) for s in sources)],
            ],
        ),
        "",
        f"The two test sets share {e.test_overlap} items; A0 trains on {e.a0_train_holds_a1_test} of A1's test items.",
        "",
        *(f"- {line}" for line in e.reading),
        "",
        "## The paired common-evaluation design (C0 / C1)",
        "",
        "**What changes between conditions?**",
        "",
        *(f"- {c}" for c in r.designs[0].changes),
        "",
        "**What remains constant?**",
        "",
        *(f"- {c}" for c in r.designs[0].constant),
        "",
        "The test set has two parts. *Probes* are test items whose group-mates C0 trains on; "
        "*controls* are whole groups that neither condition trains on. C0 - C1 on the probes "
        "estimates the effect of training on group-mates of a test item; on the controls it "
        "should be close to zero, which makes them a negative control for the swap. Probes and "
        "controls are different kinds of items (probes sit in groups, controls are mostly "
        "singletons): each is compared between C0 and C1, never with the other.",
        "",
    ]
    params = r.designs[0].params
    lines += [
        "Parameters (every design): "
        + ", ".join(f"{k} {v}" for k, v in params.items())
        + ". Groups larger than `max_group` stay whole in training.",
        "",
        "In the condition tables, *M3 pairs train-test* counts M3 candidate pairs, by machine "
        "category, with one image in train and one in test. REVIEW_REQUIRED pairs are pHash-only "
        "(the M3 review and family levels coincide), and a SAME_FAMILY_OR_SCENE pair of a source "
        "whose primary level is near lies below that level; neither is a constraint, so C1 may "
        "hold them. The primary-level pairs are counted in the column before.",
        "",
    ]
    for d in r.designs:
        by = {c.name: c for c in d.conditions}
        lines += [
            f"### Design {d.seed}",
            "",
            "Roles: "
            + ", ".join(f"{k} {_n(v)}" for k, v in d.roles.items())
            + f" (file `{d.roles_file}`).",
            "",
            *_table(
                ["test part", "items", *(f"`{s}`" for s in sources)],
                [
                    [
                        "probes (exposed in C0)",
                        _n(sum(d.probes.values())),
                        *(_n(d.probes[s]) for s in sources),
                    ],
                    [
                        "controls",
                        _n(sum(d.controls.values())),
                        *(_n(d.controls[s]) for s in sources),
                    ],
                ],
            ),
            "",
            "How each probe is linked to its mates (the strongest direct link): "
            + ", ".join(f"{k} {_n(v)}" for k, v in d.probe_links.items())
            + ". *Similar pair* means an M3 pair at the source's primary level; *same metadata "
            "group* means the same production batch or design family without such a pair.",
            "",
            *_table(
                ["split", "items", *(f"`{s}`" for s in sources)],
                _split_rows(by["C0"].items, sources),
            ),
            "",
            "(C0; C1 has the same counts per split and source: "
            + (
                "yes"
                if d.train_items_equal_by_source and by["C0"].items == by["C1"].items
                else "NO"
            )
            + ".)",
            "",
            *_table(
                [
                    "condition",
                    "file",
                    "exposed test items",
                    "constraint groups crossing",
                    "primary-level pairs crossing",
                    "M3 pairs train-test",
                ],
                [
                    [
                        c.name,
                        f"`{c.file}`",
                        _n(c.exposed_test_items),
                        ", ".join(
                            f"{k} {v}" for k, v in c.measure.constraints_crossing.items() if v
                        )
                        or "0",
                        _n(c.measure.primary_pairs_crossing),
                        ", ".join(f"{k} {v}" for k, v in c.measure.pairs_train_test.items()) or "0",
                    ]
                    for c in d.conditions
                ],
            ),
            "",
            "Training boxes per class, C0 minus C1: "
            + ", ".join(f"{k} {v:+d}" for k, v in d.train_box_difference.items())
            + "; replacement matches: "
            + ", ".join(f"{k} {v}" for k, v in d.replacements.items())
            + " (profile = the same boxes per class).",
            "",
            "Shortfalls against the targets: "
            + "; ".join(
                f"`{s}` " + ", ".join(f"{k} {v}" for k, v in values.items() if v)
                for s, values in d.shortfalls.items()
                if any(values.values())
            )
            + ".",
            "",
        ]
    lines += [
        "## Two source-held-out regimes",
        "",
        "- **B-strict** (the M5 split `B-<source>`): the held-out source is the test set, and training items that share a constraint *directly* with a held-out item are excluded. It asks how a model generalizes when both source identity and the known machine-similarity overlap are removed.",
        "- **B-natural** (new): the held-out source is the test set and every other item is available for training and validation (group-aware), including items a machine similarity component links to the held-out source. It asks how a model generalizes to an unseen acquisition source under naturally occurring cross-source similarity.",
        "",
        "The historical name `B` stays the file name of B-strict.",
        "",
        *_table(
            [
                "fold",
                "regime",
                "file",
                "train",
                "val",
                "test",
                "excluded",
                "pure",
                "constraints crossing",
                "primary pairs crossing",
                "training items linked to test",
            ],
            [
                [
                    f"`{h.fold}`",
                    h.regime,
                    f"`{h.file}`",
                    _n(sum(h.items.get("train", {}).values())),
                    _n(sum(h.items.get("val", {}).values())),
                    _n(sum(h.items.get("test", {}).values())),
                    _n(h.excluded),
                    "yes" if h.pure else "NO",
                    _n(h.measure.supplied_groups_crossing),
                    _n(h.measure.primary_pairs_crossing),
                    _n(h.linked_training_items),
                ]
                for h in r.held_out
            ],
        ),
        "",
        "*Training items linked to test*: training or validation items whose A1 constraint group "
        "(the transitive union of all constraints) also holds a test item. B-strict excludes only "
        "the items that share a single constraint with a held-out item, so transitive links can "
        "remain; B-natural keeps every link.",
        "",
    ]
    return "\n".join(lines)


